/**
 * Generates docs/requirements-traceability.md from the real content.
 * Run: npm run docs:trace
 *
 * For every topic from the original prompt (module `topics`), it searches that module's
 * lesson text, questions, problems and interview prompts for the topic's key words.
 *   Covered  – the topic is explicitly taught/assessed in the module's content
 *   Partial  – only some of its key words appear (taught in passing)
 *   Gap      – mapped to the module but not found in its content (roadmap item)
 */
import { writeFileSync } from 'node:fs';
import { FLASHCARDS, INTERVIEWS, MODULES, PROBLEMS, QUESTIONS } from '../src/content/index';
import { PROJECT } from '../src/content/projects';

const STOP = new Set(['and', 'the', 'of', 'for', 'to', 'a', 'in', 'vs', 'with', 'how', 'your', 'you', 'do', 'what', 'tell', 'me', 'about', 'design', 'basic', 'basics', 'testing', 'test', 'tests']);

/** British/American spelling and simple plurals shouldn't decide coverage. */
function norm(s: string): string {
  return s.toLowerCase().replace(/isation/g, 'ization').replace(/ising/g, 'izing').replace(/ise\b/g, 'ize');
}

function words(topic: string): string[] {
  return norm(topic)
    .replace(/[^a-z0-9+#/ ]/g, ' ')
    .split(/[\s/]+/)
    .filter((w) => w.length > 2 && !STOP.has(w))
    .map((w) => (w.length > 4 && w.endsWith('s') && !w.endsWith('ss') ? w.slice(0, -1) : w));
}

function moduleText(id: string): string {
  const m = MODULES.find((x) => x.id === id)!;
  const parts: string[] = [m.summary];
  for (const l of m.lessons) {
    parts.push(l.title);
    for (const s of l.sections) {
      parts.push(s.title);
      if (s.kind === 'learn') parts.push(s.body);
      if (s.kind === 'visual') parts.push(s.caption);
      if (s.kind === 'build') parts.push(s.task, ...s.acceptance);
    }
  }
  for (const q of QUESTIONS.filter((x) => x.moduleId === id)) parts.push(q.prompt, q.explanation, ...q.options.map((o) => o.text));
  for (const p of PROBLEMS.filter((x) => x.moduleId === id)) parts.push(p.title, p.statement, p.solution.explanation);
  for (const iv of INTERVIEWS.filter((x) => x.revision.includes(id))) parts.push(iv.prompt, iv.modelAnswer, ...iv.rubric.map((r) => r.point));
  for (const f of FLASHCARDS.filter((x) => x.moduleId === id)) parts.push(f.front, f.back);
  // The capstone's detailed roadmap lives in projects.ts (rendered on the Projects page).
  if (id === 'm24') {
    parts.push(PROJECT.architecture, PROJECT.buildOptions);
    for (const ph of PROJECT.phases) {
      parts.push(ph.title, ph.goal);
      for (const t of ph.tasks) parts.push(t.title, t.brief, ...t.deliverables, ...t.acceptance, t.review);
    }
  }
  return norm(parts.join('\n'));
}

const rows: string[] = [];
const summary: { id: string; title: string; topics: number; covered: number; partial: number; gap: number }[] = [];

for (const m of MODULES) {
  const text = moduleText(m.id);
  const q = QUESTIONS.filter((x) => x.moduleId === m.id).length;
  const p = PROBLEMS.filter((x) => x.moduleId === m.id).length;
  const iv = INTERVIEWS.filter((x) => x.revision[0] === m.id).length;
  const lessons = m.lessons.map((l) => l.id).join(', ');
  let covered = 0;
  let partial = 0;
  let gap = 0;
  for (const t of m.topics) {
    const ws = words(t);
    const hits = ws.filter((w) => text.includes(w)).length;
    const status = ws.length === 0 || hits === ws.length ? 'Covered' : hits > 0 ? 'Partial' : 'Gap';
    if (status === 'Covered') covered++;
    else if (status === 'Partial') partial++;
    else gap++;
    rows.push(`| ${t} | M${m.number} ${m.title} | ${m.level} | ${lessons || '—'} | ${q} Q · ${p} P · ${iv} IV | ${status} | \`src/content/modules/${m.id}*.ts\` |`);
  }
  summary.push({ id: m.id, title: m.title, topics: m.topics.length, covered, partial, gap });
}

const totals = summary.reduce((a, s) => ({ topics: a.topics + s.topics, covered: a.covered + s.covered, partial: a.partial + s.partial, gap: a.gap + s.gap }), { topics: 0, covered: 0, partial: 0, gap: 0 });

const md = `# Requirements traceability matrix

_Generated by \`npm run docs:trace\` from the shipped content on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand._

**Source of requirements:** every topic bullet of the original 30-part prompt (\`Study/Cursor Pro SDET 3 + QA Lead Master Interview Preparation Prompt.md\`) plus the SDET Quest build brief, mapped to the module that owns it (\`src/content/outline.ts\`).

**How status is computed (automatically, not by opinion):** the generator searches each module's lesson text, questions, problems, interview prompts/rubrics and flashcards for the topic's key words.
- **Covered** – all key words found: the topic is taught and/or assessed.
- **Partial** – some key words found: touched on, worth deepening.
- **Gap** – mapped but not found in the content: a roadmap item.

Keyword matching can be fooled (a word may appear without real teaching), so treat this as a strong signal, not proof. Evidence of *learning* is the learner's own attempt history, visible on the Progress page.

## Summary

| Module | Topics | Covered | Partial | Gap |
|---|---|---|---|---|
${summary.map((s) => `| ${s.id.toUpperCase()} ${s.title} | ${s.topics} | ${s.covered} | ${s.partial} | ${s.gap} |`).join('\n')}
| **Total** | **${totals.topics}** | **${totals.covered}** | **${totals.partial}** | **${totals.gap}** |

Legend for assessments: Q = graded questions, P = coding/SQL/Java problems, IV = interview questions whose primary revision module is this one.

## Topic → module → lessons → assessments → status → evidence

| Topic (original requirement) | Module | Level | Lessons | Assessments | Status | Evidence |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;

writeFileSync('docs/requirements-traceability.md', md);
console.log(`Wrote docs/requirements-traceability.md: ${totals.topics} topics, ${totals.covered} covered, ${totals.partial} partial, ${totals.gap} gap.`);
for (const s of summary) if (s.gap) console.log(`  ${s.id}: ${s.gap} gap(s)`);
